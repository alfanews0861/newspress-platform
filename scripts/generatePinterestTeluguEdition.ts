// Helper for building placement block
function createBlock(config: {
  placementId: string;
  pageId: string;
  articleId: string;
  articleTitle: string;
  subheadline?: string;
  byline: string;
  category: string;
  leadParagraph?: string;
  bodyContent: string;
  x: number;
  y: number;
  width: number;
  height: number;
  colStart: number;
  colSpan: number;
  layoutRole: StoryLayoutRole;
  styleVariant: 'lead_banner' | 'anchor_box' | 'photo_feature' | 'column_card' | 'sidebar_brief' | 'standard';
  kicker: string;
  headlineFont: string;
  headlineSize: number;
  headlineColor?: string;
  accentColor?: string;
  cardBackground?: string;
  imageUrl?: string;
  imageCaption?: string;
  imagePlacement?: 'top' | 'none';
  imageHeight?: number;
  bulletPoints?: string[];
}): ArticlePlacement {
  return {
    placementId: config.placementId,
    editionId: teluguEdition.editionId,
    pageId: config.pageId,
    tenantId: teluguEdition.tenantId,
    newsId: config.articleId,
    articleTitle: config.articleTitle,
    subheadline: config.subheadline,
    byline: config.byline,
    category: config.category,
    leadParagraph: config.leadParagraph,
    bodyContent: config.bodyContent,
    x: config.x,
    y: config.y,
    width: config.width,
    height: config.height,
    columnStart: config.colStart,
    columnSpan: config.colSpan,
    rowStart: Math.round((config.y - 24) / 18),
    rowSpan: Math.round(config.height / 18),
    headlineSize: config.headlineSize,
    headlineFont: config.headlineFont,
    headlineColor: config.headlineColor || '#0f172a',
    bodyFontSize: 12, // User Requirement: Strictly 12px Mallanna body font
    imagePlacement: config.imagePlacement || 'top',
    imageHeight: config.imageHeight || 130,
    imageUrl: config.imageUrl,
    imageCaption: config.imageCaption,
    layoutRole: config.layoutRole,
    status: 'placed',
    locked: true,
    styleVariant: config.styleVariant,
    kicker: config.kicker,
    accentColor: config.accentColor || '#991b1b',
    cardBackground: config.cardBackground || '#ffffff',
    bulletPoints: config.bulletPoints,
    priority: {
      editorialPriority: 9,
      breakingStatus: config.layoutRole === 'LEAD',
      articleType: config.category,
      freshnessHours: 1,
      section: 'Front Page',
      wordCount: 180,
      hasImage: !!config.imageUrl,
      publisherPriority: 9,
      calculatedScore: 100,
    },
  };
}

